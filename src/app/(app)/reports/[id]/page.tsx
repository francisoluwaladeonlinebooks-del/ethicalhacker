import Link from 'next/link';
import { notFound } from 'next/navigation';
import { isUuid } from '@/lib/ids';
import { pageContext, query } from '@/lib/page-context';
import { getReport } from '@/lib/reporting/report';
import { can } from '@/lib/rbac';
import { NotFoundError } from '@/lib/errors';
import {
  Card, CardHeader, CardBody, PageHeader, Badge, StatusBadge, DescriptionList, TableWrap, Field,
  DataQualityNote, formatDate,
} from '@/components/ui';
import { publishReportAction, reviewReportAction, submitReportAction } from '@/app/actions/reports';
import { Csrf } from '@/components/csrf';

export const dynamic = 'force-dynamic';

export default async function ReportDetailPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  if (!isUuid(id)) notFound();
  const ctx = await pageContext('report:read');
  const data = await query(ctx, async (tx) => {
    try {
      return await getReport(tx, ctx, id);
    } catch (error) {
      if (error instanceof NotFoundError) return null;
      throw error;
    }
  });
  if (!data) notFound();

  const { report, approvals } = data as any;
  const snapshot = report.snapshot ?? {};
  const summary = snapshot.summary ?? {};
  const findings: any[] = snapshot.findings ?? [];
  const notAssessed: any[] = snapshot.notAssessed ?? [];
  const coverage: any[] = snapshot.coverage ?? [];
  const canApprove = can(ctx.user, 'report:approve') && report.generated_by !== ctx.user.id;
  const isAuthor = report.generated_by === ctx.user.id;

  return (
    <>
      <PageHeader
        title={report.title}
        description={
          <span>
            {String(report.report_type).replace(/_/g, ' ')} · {report.institution_name ?? 'Supervisory portfolio'}
            {report.engagement_code ? ` · ${report.engagement_code}` : ''} · generated by {report.generated_by_name ?? 'system'} on {formatDate(report.generated_at, true)}
          </span>
        }
        meta={
          <>
            <StatusBadge status={report.status} />
            <Badge tone="slate">version {report.version}</Badge>
            <Badge tone="red">confidential supervisory material</Badge>
            {report.data_mode === 'demo' ? <Badge tone="amber">demonstration data</Badge> : null}
          </>
        }
        actions={
          <>
            <Link href="/reports" className="btn btn-secondary">All reports</Link>
            <a className="btn btn-secondary" href={`/api/reports/${report.id}/export?format=pdf`}>Download PDF</a>
            <a className="btn btn-secondary" href={`/api/reports/${report.id}/export?format=xlsx`}>Download XLSX</a>
            <a className="btn btn-ghost" href={`/api/reports/${report.id}/export?format=json`}>JSON</a>
          </>
        }
      />

      <div className="grid gap-4 xl:grid-cols-3">
        <div className="space-y-4 xl:col-span-2">
          <Card>
            <CardHeader title="Snapshot summary" subtitle="Counts are frozen at generation time. Regenerating creates a new report version." />
            <CardBody>
              <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
                {[
                  ['Confirmed', summary.confirmed ?? 0, 'Independently verified'],
                  ['Suspected', summary.suspected ?? 0, 'Verification outstanding'],
                  ['Observations', summary.observation ?? 0, 'Unscored or advisory'],
                  ['Rejected', summary.rejected ?? 0, 'Not a weakness'],
                ].map(([label, value, hint]) => (
                  <div key={String(label)} className="rounded border border-[var(--ficap-border)] p-2">
                    <p className="label">{label}</p>
                    <p className="text-xl font-semibold tabular-nums">{String(value)}</p>
                    <p className="text-2xs text-[var(--ficap-muted)]">{hint}</p>
                  </div>
                ))}
              </div>
              <div className="mt-3">
                <DescriptionList
                  items={[
                    { label: 'Highest technical severity', value: String(summary.highestSeverity ?? 'none').toUpperCase() },
                    { label: 'Blocked checks', value: String(summary.blockedChecks ?? 0) },
                    { label: 'Not assessed', value: String(summary.notAssessedChecks ?? 0) },
                    { label: 'Remediation verified', value: String(summary.verifiedRemediation ?? 0) },
                    { label: 'Remediation overdue', value: String(summary.overdueRemediation ?? 0) },
                    { label: 'Framework versions', value: (snapshot.frameworkVersions ?? []).map((f: any) => `${f.key} ${f.version}`).join(', ') || 'none recorded' },
                  ]}
                />
              </div>
            </CardBody>
          </Card>

          <Card>
            <CardHeader title="Findings in this snapshot" subtitle="Classification is preserved exactly as it was when the report was generated." />
            {findings.length ? (
              <TableWrap maxHeight="420px">
                <table className="table">
                  <thead><tr><th>Reference</th><th>Title</th><th>Classification</th><th>Severity</th><th>CVSS</th><th>Status</th></tr></thead>
                  <tbody>
                    {findings.map((finding: any) => (
                      <tr key={finding.reference}>
                        <td className="whitespace-nowrap font-mono text-2xs">{finding.reference}</td>
                        <td className="max-w-[24rem] text-2xs">{finding.title}</td>
                        <td className="text-2xs"><Badge tone={finding.classification === 'confirmed' ? 'red' : finding.classification === 'suspected' ? 'amber' : 'slate'}>{finding.classification}</Badge></td>
                        <td className="text-2xs capitalize">{finding.technicalSeverity}</td>
                        <td className="font-mono text-2xs">{finding.cvssScore === null ? '—' : Number(finding.cvssScore).toFixed(1)}</td>
                        <td className="text-2xs capitalize">{String(finding.status).replace(/_/g, ' ')}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </TableWrap>
            ) : (
              <CardBody><p className="prose-note">The snapshot contains no finding. That is not evidence the scope is free of weaknesses.</p></CardBody>
            )}
          </Card>

          <Card>
            <CardHeader title="Not assessed and blocked" subtitle="Listed individually so a reader cannot mistake an untested area for a clean result." />
            <CardBody>
              {notAssessed.length ? (
                <ul className="space-y-1 text-2xs">
                  {notAssessed.slice(0, 40).map((item: any, index: number) => (
                    <li key={`${item.checkKey}-${index}`} className="border-b border-dashed border-[var(--ficap-border)] py-1">
                      <span className="font-mono">{item.itemCode ?? item.code}</span> · {item.checkKey} · <span className="capitalize">{item.status}</span> — {item.reason}
                    </li>
                  ))}
                  {notAssessed.length > 40 ? <li>… {notAssessed.length - 40} more in the export.</li> : null}
                </ul>
              ) : (
                <p className="prose-note">Every planned check recorded an outcome for this scope.</p>
              )}
              {coverage.length ? (
                <div className="mt-3">
                  <TableWrap>
                    <table className="table">
                      <thead><tr><th>Framework</th><th>Version</th><th>Executed</th><th>Passed</th><th>Failed</th><th>Needs verification</th><th>Blocked</th><th>Not assessed</th></tr></thead>
                      <tbody>
                        {coverage.map((row: any) => (
                          <tr key={`${row.framework_key}-${row.framework_version}`}>
                            <td className="text-2xs">{row.framework_key}</td>
                            <td className="font-mono text-2xs">{row.framework_version}</td>
                            <td className="text-right font-mono text-2xs">{row.planned}</td>
                            <td className="text-right font-mono text-2xs">{row.passed}</td>
                            <td className="text-right font-mono text-2xs">{row.failed}</td>
                            <td className="text-right font-mono text-2xs">{row.needs_verification}</td>
                            <td className="text-right font-mono text-2xs">{row.blocked}</td>
                            <td className="text-right font-mono text-2xs">{row.not_assessed}</td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </TableWrap>
                </div>
              ) : null}
            </CardBody>
          </Card>
        </div>

        <div className="space-y-4">
          <Card>
            <CardHeader title="Review and approval" subtitle="Separation of duties: the author can never approve their own report." />
            <CardBody>
              <DescriptionList
                items={[
                  { label: 'Status', value: <StatusBadge status={report.status} /> },
                  { label: 'Generated by', value: report.generated_by_name ?? '—' },
                  { label: 'Approved by', value: report.approved_by_name ?? 'not approved' },
                  { label: 'Approved at', value: report.approved_at ? formatDate(report.approved_at, true) : '—' },
                  { label: 'Published at', value: report.published_at ? formatDate(report.published_at, true) : '—' },
                ]}
              />

              {['draft', 'changes_requested'].includes(report.status) && isAuthor ? (
                <form action={submitReportAction} className="mt-3">
                  <Csrf />
                  <input type="hidden" name="reportId" value={report.id} />
                  <button className="btn btn-primary btn-sm" type="submit">Submit for independent review</button>
                </form>
              ) : null}

              {report.status === 'in_review' && canApprove ? (
                <form action={reviewReportAction} className="mt-3 space-y-2 border-t border-[var(--ficap-border)] pt-3">
                  <Csrf />
                  <input type="hidden" name="reportId" value={report.id} />
                  <Field label="Decision" name="decision" required>
                    <select name="decision" className="input" required>
                      <option value="approve">Approve</option>
                      <option value="return">Return for changes</option>
                      <option value="comment">Record a comment only</option>
                    </select>
                  </Field>
                  <Field label="Basis for the decision" name="comments" hint="Approval requires at least 20 characters describing what was checked.">
                    <textarea name="comments" rows={3} className="input" required minLength={10} />
                  </Field>
                  <button className="btn btn-primary btn-sm" type="submit">Record decision</button>
                </form>
              ) : null}

              {report.status === 'in_review' && isAuthor ? (
                <p className="mt-3 rounded border border-amber-200 bg-amber-50 p-2 text-2xs text-amber-900">
                  You generated this report, so you cannot approve it. An independent reviewer must record the decision.
                </p>
              ) : null}

              {report.status === 'approved' && can(ctx.user, 'report:publish') ? (
                <form action={publishReportAction} className="mt-3 border-t border-[var(--ficap-border)] pt-3">
                  <Csrf />
                  <input type="hidden" name="reportId" value={report.id} />
                  <button className="btn btn-secondary btn-sm" type="submit">Publish to the supervisory record</button>
                </form>
              ) : null}
            </CardBody>
          </Card>

          <Card>
            <CardHeader title="Review history" />
            <CardBody>
              {approvals.length ? (
                <ol className="space-y-2 text-2xs">
                  {approvals.map((approval: any) => (
                    <li key={approval.id} className="border-l-2 border-[var(--ficap-border)] pl-2">
                      <div className="font-medium capitalize">{approval.decision} · {approval.reviewer_name} ({String(approval.reviewer_role).replace(/_/g, ' ')})</div>
                      <div className="text-[var(--ficap-muted)]">{formatDate(approval.created_at, true)}</div>
                      {approval.comments ? <p className="mt-1">{approval.comments}</p> : null}
                    </li>
                  ))}
                </ol>
              ) : (
                <p className="prose-note">No review decision recorded.</p>
              )}
            </CardBody>
          </Card>

          <Card>
            <CardHeader title="Limitations" subtitle="Reproduced from the snapshot." />
            <CardBody>
              <ul className="space-y-1 text-2xs leading-relaxed text-[var(--ficap-muted)]">
                {(snapshot.limitations ?? []).map((limitation: string, index: number) => <li key={index}>· {limitation}</li>)}
              </ul>
            </CardBody>
          </Card>

          <DataQualityNote>
            Exports are generated from the stored snapshot, not recalculated. Downloading a report is an audited action and is restricted to roles holding
            report-read permission.
          </DataQualityNote>
        </div>
      </div>
    </>
  );
}
